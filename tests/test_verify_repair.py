SCHEMA_PATH = (
    ROOT / "docs" / "schemas" / "repair-verification.v1.json"
)


class SchemaConsistencyTests(unittest.TestCase):
    """The published JSON Schema and the code must agree — the wave-3
    drift-guard discipline applied to the wave-4 report."""

    def _schema(self):
        return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))

    def test_schema_file_is_valid_json_with_contract_markers(self):
        schema = self._schema()
        self.assertEqual(
            schema["properties"]["schema"]["const"],
            "mizan.repair-verification.v1",
        )
        self.assertEqual(
            schema["properties"]["request"]["properties"]["schema"]["const"],
            "repair-request.v1",
        )
        self.assertEqual(
            schema["properties"]["human_review_required"]["const"], True
        )
        self.assertEqual(
            schema["properties"]["worktree"]["properties"]["created"]
            ["const"], True,
        )
        self.assertEqual(
            schema["properties"]["patch"]["properties"]["applied"]
            ["const"], True,
        )
        self.assertEqual(
            schema["properties"]["tests"]["properties"]["environment"]
            ["properties"]["secrets_scrubbed"]["const"], True,
        )
        self.assertEqual(
            schema["properties"]["tests"]["properties"]["environment"]
            ["properties"]["network"]["enum"],
            ["proxies-stripped-default", "allowed-by-explicit-flag"],
        )
        self.assertEqual(
            schema["properties"]["checks"]["minItems"], 3,
            "the three measured checks are the floor of the report",
        )

    def test_report_shape_is_covered_by_schema(self):
        schema = self._schema()
        required = set(schema["required"])
        with tempfile.TemporaryDirectory() as td:
            work = Path(td)
            repo = _make_repo(work / "repo")
            request = _fixture_request(repo)
            patch = _patch_for(repo, FIXED_APP)
            patch_path = work / "fix.patch"
            patch_path.write_text(patch, encoding="utf-8")
            report = run_verification(
                _write_json(work / "request.json", request),
                patch_path,
                repo,
                tests_command="true",
            )
        self.assertLessEqual(
            set(report.keys()), required,
            "the code builds report fields the published schema does "
            "not declare — schemas must not drift from code",
        )
        # the report itself must satisfy the schema's required blocks:
        # every emitted field must be DECLARED, every required field
        # must be present
        for block, spec in (
            ("worktree", schema["properties"]["worktree"]),
            ("patch", schema["properties"]["patch"]),
            ("finding_check", schema["properties"]["finding_check"]),
            ("tests", schema["properties"]["tests"]),
            ("transfer", schema["properties"]["transfer"]),
        ):
            self.assertLessEqual(
                set(report[block].keys()),
                set(spec["properties"].keys()),
                f"block {block} carries fields the schema does not "
                f"declare",
            )
            for key in spec.get("required", []):
                self.assertIn(
                    key, report[block],
                    f"block {block} is missing required field {key}",
                )
        # checks: measured floor present with status enum values only
        statuses = {c["status"] for c in report["checks"]}
        self.assertIn("measured", statuses)
        for check in report["checks"]:
            self.assertIn(check["status"],
                          schema["properties"]["checks"]["items"]
                          ["properties"]["status"]["enum"])


