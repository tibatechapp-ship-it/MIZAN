"""Wave-4 contract tests — the isolated repair verification.

Acceptance gate from the plan (docs/DEV_PLAN_V0150.md, Wave 4):

* the patch is applied ONLY inside an isolated ``git worktree``
  (detached HEAD) — the user's tree is never written;
* tests run with NO secrets and NO network in the environment by
  default — the scrubbing is honest (audited in the report, limits
  declared, not oversold);
* the report records the changed files, which tests ran and which did
  not, the persistence of the original finding fingerprint, and the
  isolation limits;
* transfer is gated: ``--approve`` is required, an unverified patch is
  never transferred, the worktree is disposed (or explicitly kept) —
  transfer or delete, nothing else;
* exit contract: 0 verified, 1 verification measured a failure,
  2 refusal naming path and reason.
"""

import json
import os
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from mizan.analyzer import analyze_repository
from mizan.cli import main
from mizan.integrations.repair_request import build_repair_request
from mizan.integrations.sarif_import import _fallback_fingerprint
from mizan.integrations.verify_repair import (
    VERIFY_SCHEMA,
    VerifyRepairError,
    build_verification_env,
    run_verification,
)

VULN_APP = (
    "def handle(expr):\n"
    "    return eval(expr)\n"
)

FIXED_APP = (
    "import ast\n"
    "\n"
    "\n"
    "def handle(expr):\n"
    "    return ast.literal_eval(expr)\n"
)

FIXTURE_TEST = (
    "import unittest\n"
    "import app\n"
    "\n"
    "\n"
    "class HandleTests(unittest.TestCase):\n"
    "    def test_literal(self):\n"
    "        self.assertEqual(app.handle(\"[1, 2]\"), [1, 2])\n"
)


def _git(args, cwd):
    subprocess.run(
        ["git", *args], cwd=str(cwd), check=True, capture_output=True,
        text=True,
        env={
            **os.environ,
            "GIT_AUTHOR_NAME": "wave4-test",
            "GIT_AUTHOR_EMAIL": "wave4@test",
            "GIT_COMMITTER_NAME": "wave4-test",
            "GIT_COMMITTER_EMAIL": "wave4@test",
        },
    )


def _make_repo(root: Path) -> Path:
    """A tiny measured fixture: one vulnerable file, one green test."""
    root.mkdir(parents=True, exist_ok=True)
    (root / "app.py").write_text(VULN_APP, encoding="utf-8")
    tests_dir = root / "tests"
    tests_dir.mkdir(exist_ok=True)
    (tests_dir / "__init__.py").write_text("", encoding="utf-8")
    (tests_dir / "test_app.py").write_text(
        FIXTURE_TEST, encoding="utf-8"
    )
    _git(["init", "-q"], root)
    _git(["add", "--all"], root)
    _git(["commit", "--quiet", "-m", "fixture"], root)
    return root


def _patch_for(root: Path, new_app: str,
               extra_files: dict[str, str] | None = None) -> str:
    """Produce the unified diff of replacing app.py content (and any
    extra files) at HEAD — generated by git itself, never hand-counted
    hunk headers. New files need ``add -N``: a plain ``git diff``
    ignores untracked paths, which would silently shrink the patch."""
    (root / "app.py").write_text(new_app, encoding="utf-8")
    for name, content in (extra_files or {}).items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    _git(["add", "-N", "--all"], root)
    diff = subprocess.run(
        ["git", "diff"], cwd=str(root), capture_output=True, text=True,
        check=True,
    ).stdout
    # restore the pristine HEAD state, including added files
    subprocess.run(
        ["git", "reset", "--quiet", "HEAD", "--"], cwd=str(root),
        capture_output=True, text=True, check=True,
    )
    subprocess.run(
        ["git", "checkout", "--", "."], cwd=str(root),
        capture_output=True, text=True, check=True,
    )
    for name in (extra_files or {}):
        path = root / name
        if path.exists():
            path.unlink()
    return diff


def _fixture_request(root: Path) -> dict:
    analysis = analyze_repository(str(root))
    findings = [
        f for f in analysis["findings"]
        if f["rule"] == "dynamic-execution"
    ]
    assert findings, "the fixture must carry a dynamic-execution finding"
    return build_repair_request(findings[0])


def _write_json(path: Path, payload) -> Path:
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    return path


class EnvScrubbingTests(unittest.TestCase):
    def test_secret_named_vars_are_removed_and_audited(self):
        os.environ["WAVE4_TEST_TOKEN"] = "x"
        os.environ["WAVE4_TEST_SECRET_KEY"] = "x"
        os.environ["GITHUB_TOKEN_WAVE4"] = "x"
        try:
            env, audit = build_verification_env(allow_network=True)
        finally:
            for name in ("WAVE4_TEST_TOKEN", "WAVE4_TEST_SECRET_KEY",
                         "GITHUB_TOKEN_WAVE4"):
                os.environ.pop(name, None)
        self.assertNotIn("WAVE4_TEST_TOKEN", env)
        self.assertNotIn("WAVE4_TEST_SECRET_KEY", env)
        self.assertNotIn("GITHUB_TOKEN_WAVE4", env)
        self.assertTrue(audit["secrets_scrubbed"])
        for name in ("WAVE4_TEST_TOKEN", "WAVE4_TEST_SECRET_KEY",
                     "GITHUB_TOKEN_WAVE4"):
            self.assertIn(name, audit["scrubbed_var_names"])
        self.assertEqual(audit["scrubbed_var_count"],
                         len(audit["scrubbed_var_names"]))

    def test_ordinary_vars_survive_scrubbing(self):
        os.environ["WAVE4_PLAIN_VAR"] = "keep-me"
        try:
            env, _ = build_verification_env(allow_network=True)
        finally:
            os.environ.pop("WAVE4_PLAIN_VAR", None)
        self.assertEqual(env.get("WAVE4_PLAIN_VAR"), "keep-me")

    def test_network_proxies_stripped_by_default(self):
        os.environ["HTTP_PROXY"] = "http://proxy.example:9"
        os.environ["https_proxy"] = "http://proxy.example:9"
        try:
            env, audit = build_verification_env(allow_network=False)
            self.assertNotIn("HTTP_PROXY", env)
            self.assertNotIn("https_proxy", env)
            self.assertEqual(audit["network"], "proxies-stripped-default")
            self.assertIn("HTTP_PROXY", audit["network_vars_removed"])

            env2, audit2 = build_verification_env(allow_network=True)
        finally:
            os.environ.pop("HTTP_PROXY", None)
            os.environ.pop("https_proxy", None)
        self.assertEqual(env2.get("HTTP_PROXY"), "http://proxy.example:9")
        self.assertEqual(audit2["network"], "allowed-by-explicit-flag")


class RefusalTests(unittest.TestCase):
    """Exit-2 semantics: every refusal names the path and the reason,
    and none of them creates a worktree."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.work = Path(self.temp.name)
        self.repo = _make_repo(self.work / "repo")
        self.request = _fixture_request(self.repo)
        self.patch = _patch_for(self.repo, FIXED_APP)

    def tearDown(self):
        self.temp.cleanup()

    def _run(self, request_path=None, patch_path=None, **kwargs):
        return run_verification(
            request_path=request_path or _write_json(
                self.work / "request.json", self.request),
            patch_path=patch_path or self._patch_file(),
            repo_path=self.repo,
            tests_command="true",
            **kwargs,
        )

    def _patch_file(self, patch=None) -> Path:
        path = self.work / "fix.patch"
        path.write_text(patch if patch is not None else self.patch,
                        encoding="utf-8")
        return path

    def test_missing_request_file_names_the_path(self):
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(request_path=self.work / "nope.json")
        self.assertIn("nope.json", str(ctx.exception))

    def test_invalid_json_request_names_the_path(self):
        bad = self.work / "bad.json"
        bad.write_text("{not json", encoding="utf-8")
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(request_path=bad)
        self.assertIn("bad.json", str(ctx.exception))

    def test_wrong_schema_marker_is_refused(self):
        tampered = dict(self.request)
        tampered["schema"] = "repair-request.v2"
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(request_path=_write_json(
                self.work / "r2.json", tampered))
        self.assertIn("repair-request.v1", str(ctx.exception))

    def test_request_without_human_review_is_refused(self):
        tampered = dict(self.request)
        tampered["human_review_required"] = False
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(request_path=_write_json(
                self.work / "r3.json", tampered))
        self.assertIn("human_review_required", str(ctx.exception))

    def test_batch_of_two_is_refused(self):
        batch = {
            "schema": "repair-request.v1",
            "count": 2,
            "requests": [self.request, self.request],
            "human_review_required": True,
        }
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(request_path=_write_json(
                self.work / "r4.json", batch))
        self.assertIn("ONE repair request", str(ctx.exception))

    def test_single_request_batch_is_accepted(self):
        batch = {
            "schema": "repair-request.v1",
            "count": 1,
            "requests": [self.request],
            "human_review_required": True,
        }
        report = self._run(request_path=_write_json(
            self.work / "r5.json", batch))
        self.assertTrue(report["verified"])

    def test_missing_patch_file_names_the_path(self):
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(patch_path=self.work / "gone.patch")
        self.assertIn("gone.patch", str(ctx.exception))

    def test_empty_patch_is_refused(self):
        empty = self.work / "empty.patch"
        empty.write_text("", encoding="utf-8")
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(patch_path=empty)
        self.assertIn("empty", str(ctx.exception))

    def test_non_diff_file_is_refused(self):
        junk = self.work / "junk.patch"
        junk.write_text("this is not a diff at all\n", encoding="utf-8")
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(patch_path=junk)
        self.assertIn("unified diff", str(ctx.exception))

    def test_corrupt_patch_is_refused_with_gits_reason(self):
        corrupt = re.sub(
            r"@@ -\d+(?:,\d+)? \+\d+(?:,\d+)? @@",
            "@@ -1,99 +1,99 @@", self.patch)
        self.assertNotEqual(corrupt, self.patch)
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(patch_path=self._patch_file(corrupt))
        self.assertIn("does not apply", str(ctx.exception))

    def test_plain_directory_is_not_a_repository(self):
        plain = self.work / "plain"
        plain.mkdir()
        with self.assertRaises(VerifyRepairError) as ctx:
            run_verification(
                request_path=_write_json(self.work / "rq.json",
                                         self.request),
                patch_path=self._patch_file(),
                repo_path=plain,
                tests_command="true",
            )
        self.assertIn("not a usable git repository", str(ctx.exception))

    def test_transfer_without_approve_is_refused_before_any_side_effect(
        self,
    ):
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(transfer_branch="wave4-branch")
        self.assertIn("--approve", str(ctx.exception))

    def test_approve_without_transfer_is_refused(self):
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(approve=True)
        self.assertIn("--transfer-branch", str(ctx.exception))

    def test_existing_branch_is_never_overwritten(self):
        _git(["branch", "taken"], self.repo)
        with self.assertRaises(VerifyRepairError) as ctx:
            self._run(transfer_branch="taken", approve=True)
        self.assertIn("already exists", str(ctx.exception))


class VerifiedPatchTests(unittest.TestCase):
    """The happy path, measured end to end on a real fixture repo."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.work = Path(self.temp.name)
        self.repo = _make_repo(self.work / "repo")
        self.request = _fixture_request(self.repo)
        self.patch = _patch_for(self.repo, FIXED_APP)
        self.request_path = _write_json(
            self.work / "request.json", self.request)
        self.patch_path = self.work / "fix.patch"
        self.patch_path.write_text(self.patch, encoding="utf-8")

    def tearDown(self):
        self.temp.cleanup()

    def test_verified_patch_passes_every_check(self):
        report = run_verification(
            self.request_path, self.patch_path, self.repo,
            tests_command=f"{sys.executable} -m unittest discover -q",
        )
        self.assertEqual(report["schema"], VERIFY_SCHEMA)
        self.assertTrue(report["verified"])
        self.assertFalse(
            report["finding_check"]["original_still_fires"])
        self.assertEqual(
            report["finding_check"]["new_findings_count"], 0)
        self.assertTrue(report["tests"]["ran"])
        self.assertTrue(report["tests"]["passed"])
        self.assertIn("unittest", report["tests"]["command"])
        self.assertEqual(report["patch"]["changed_files"], ["app.py"])
        self.assertTrue(report["patch"]["applied"])
        self.assertTrue(report["worktree"]["disposed"])
        self.assertTrue(report["transfer"]["done"] is False)
        self.assertEqual(
            report["request"]["finding_id"], self.request["finding_id"])
        self.assertEqual(
            report["finding_check"]["original_finding_id"],
            self.request["finding_id"],
        )
        self.assertEqual(len(report["isolation_limits"]), 5)
        self.assertTrue(report["human_review_required"])

    def test_fingerprint_identity_survives_the_round_trip(self):
        analysis = analyze_repository(str(self.repo))
        finding = next(
            f for f in analysis["findings"]
            if f["rule"] == "dynamic-execution"
        )
        expected = _fallback_fingerprint(
            "MIZAN", finding["rule"], finding["file"],
            finding["line"], finding["message"],
        )
        self.assertEqual(self.request["finding_id"], expected)
        report = run_verification(
            self.request_path, self.patch_path, self.repo,
            tests_command="true",
        )
        self.assertEqual(
            report["request"]["finding_id"], expected)
        self.assertEqual(
            report["finding_check"]["original_finding_id"], expected)

    def test_declared_only_verification_steps_are_marked_honestly(self):
        request = dict(self.request)
        request["verification"] = list(request["verification"]) + [
            {"what": "the security owner signs the rotation log",
             "how": "a human checks the log"},
        ]
        report = run_verification(
            _write_json(self.work / "rq2.json", request),
            self.patch_path, self.repo, tests_command="true",
        )
        statuses = {c["what"]: c["status"] for c in report["checks"]}
        self.assertEqual(statuses["the original finding no longer fires"],
                         "measured")
        self.assertEqual(statuses["no new findings of any rule appeared"],
                         "measured")
        self.assertEqual(
            statuses["the security owner signs the rotation log"],
            "declared-only")
        declared = next(
            c for c in report["checks"] if c["status"] == "declared-only")
        self.assertIsNone(declared["passed"])

    def test_worktree_is_kept_only_when_explicitly_asked(self):
        report = run_verification(
            self.request_path, self.patch_path, self.repo,
            tests_command="true", keep_worktree=True,
        )
        self.assertFalse(report["worktree"]["disposed"])
        self.assertTrue(
            Path(report["worktree"]["path"]).exists(),
            "a kept worktree must exist for human inspection",
        )
        subprocess.run(
            ["git", "worktree", "remove", "--force",
             report["worktree"]["path"]],
            cwd=str(self.repo), capture_output=True, text=True,
            check=True,
        )

    def test_output_report_is_written_when_asked(self):
        out = self.work / "report.json"
        report = run_verification(
            self.request_path, self.patch_path, self.repo,
            tests_command="true",
        )
        from mizan.integrations.verify_repair import (
            write_verification_report,
        )
        write_verification_report(report, out)
        loaded = json.loads(out.read_text(encoding="utf-8"))
        self.assertEqual(loaded["schema"], VERIFY_SCHEMA)
        self.assertTrue(loaded["verified"])

    def test_transfer_with_approval_creates_review_branch(self):
        report = run_verification(
            self.request_path, self.patch_path, self.repo,
            tests_command="true",
            transfer_branch="verified-fix", approve=True,
        )
        self.assertTrue(report["transfer"]["done"])
        self.assertTrue(report["worktree"]["disposed"])
        branches = subprocess.run(
            ["git", "branch", "--list", "verified-fix"],
            cwd=str(self.repo), capture_output=True, text=True,
        ).stdout
        self.assertIn("verified-fix", branches)
        message = subprocess.run(
            ["git", "log", "-1", "--format=%B", "verified-fix"],
            cwd=str(self.repo), capture_output=True, text=True,
        ).stdout
        self.assertIn(self.request["finding_id"], message)
        self.assertIn("human_review_required=true", message)
        # the user's tree is untouched: still at the fixture commit
        head = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=str(self.repo),
            capture_output=True, text=True,
        ).stdout.strip()
        self.assertEqual(head, report["head_before"])

    def test_unverified_patch_is_never_transferred(self):
        # a patch that "fixes" nothing: whitespace only, the finding
        # still fires — verification must fail and the transfer must
        # be refused in the report.
        noop_patch = _patch_for(self.repo, VULN_APP + "\n# touched\n")
        report = run_verification(
            self.request_path,
            self._patch(noop_patch),
            self.repo,
            tests_command="true",
            transfer_branch="should-not-exist", approve=True,
        )
        self.assertFalse(report["verified"])
        self.assertFalse(report["transfer"]["done"])
        self.assertIn("unverified", report["transfer"]["reason"])
        branches = subprocess.run(
            ["git", "branch", "--list", "should-not-exist"],
            cwd=str(self.repo), capture_output=True, text=True,
        ).stdout
        self.assertNotIn("should-not-exist", branches)

    def _patch(self, text):
        path = self.work / "noop.patch"
        path.write_text(text, encoding="utf-8")
        return path


class MeasuredFailureTests(unittest.TestCase):
    """Exit-1 semantics: the verification RAN and measured a failure —
    the report says which check failed, nothing is silent."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.work = Path(self.temp.name)
        self.repo = _make_repo(self.work / "repo")
        self.request = _fixture_request(self.repo)
        self.request_path = _write_json(
            self.work / "request.json", self.request)

    def tearDown(self):
        self.temp.cleanup()

    def _run(self, patch_text, **kwargs):
        patch_path = self.work / "p.patch"
        patch_path.write_text(patch_text, encoding="utf-8")
        return run_verification(
            self.request_path, patch_path, self.repo,
            tests_command="true", **kwargs,
        )

    def test_patch_that_does_not_fix_the_finding_fails_verification(
        self,
    ):
        # replace eval with exec — still dynamic-execution
        still_vulnerable = (
            "def handle(expr):\n"
            "    return exec(expr)\n"
        )
        patch = _patch_for(self.repo, still_vulnerable)
        report = self._run(patch)
        self.assertFalse(report["verified"])
        self.assertTrue(
            report["finding_check"]["original_still_fires"])

    def test_patch_that_introduces_a_new_finding_fails_verification(
        self,
    ):
        # fix the eval but smuggle in a hardcoded credential. The value
        # is synthetic on purpose (never a provider-shaped key —
        # GitHub push protection rightly blocks real-format test
        # fixtures) while still firing MIZAN's rule.
        patch = _patch_for(
            self.repo, FIXED_APP,
            extra_files={"config.py":
                         'password = "hunter2-real-secret-12345"\n'},
        )
        report = self._run(patch)
        self.assertFalse(report["verified"])
        self.assertGreaterEqual(
            report["finding_check"]["new_findings_count"], 1)
        new_rules = {f["rule"]
                     for f in report["finding_check"]["new_findings"]}
        self.assertIn("hardcoded-secret-candidate", new_rules)

    def test_failing_tests_fail_verification(self):
        # correct fix, but the fixture test now fails
        patch = _patch_for(
            self.repo, FIXED_APP,
            extra_files={"tests/test_app.py": (
                "import unittest\n"
                "import app\n"
                "\n"
                "\n"
                "class HandleTests(unittest.TestCase):\n"
                "    def test_literal(self):\n"
                "        self.assertEqual(app.handle(\"[1, 2]\"), 99)\n"
            )},
        )
        patch_path = self.work / "failing-tests.patch"
        patch_path.write_text(patch, encoding="utf-8")
        report = run_verification(
            self.request_path, patch_path, self.repo,
            tests_command=f"{sys.executable} -m unittest discover -q",
        )
        self.assertFalse(report["verified"])
        self.assertTrue(report["tests"]["ran"])
        self.assertFalse(report["tests"]["passed"])
        self.assertNotEqual(report["tests"]["returncode"], 0)
        # the failing checks are named in the report
        failed = [c["what"] for c in report["checks"]
                  if c["status"] == "measured" and not c["passed"]]
        self.assertIn("the project's test suite passes", failed)

    def test_timed_out_tests_never_count_as_a_pass(self):
        # correct fix, but the test command hangs — must be killed and
        # reported as failed, not silently swallowed
        patch = _patch_for(self.repo, FIXED_APP)
        patch_path = self.work / "slow.patch"
        patch_path.write_text(patch, encoding="utf-8")
        report = run_verification(
            self.request_path, patch_path, self.repo,
            tests_command="sleep 30", timeout=2,
        )
        self.assertFalse(report["verified"])
        self.assertTrue(report["tests"]["ran"])
        self.assertFalse(report["tests"]["passed"])
        self.assertIn("timed out", report["tests"]["summary"])

    def test_zero_tests_collected_never_count_as_a_pass(self):
        # the default unittest discovery on a repo with no tests is an
        # honest failure: an unverified suite cannot certify a pass
        empty_repo = self.work / "empty-repo"
        empty_repo.mkdir()
        (empty_repo / "app.py").write_text(VULN_APP, encoding="utf-8")
        _git(["init", "-q"], empty_repo)
        _git(["add", "--all"], empty_repo)
        _git(["commit", "--quiet", "-m", "no tests"], empty_repo)
        analysis = analyze_repository(str(empty_repo))
        finding = next(
            f for f in analysis["findings"]
            if f["rule"] == "dynamic-execution"
        )
        request = build_repair_request(finding)
        patch = self.work / "fix.patch"
        patch.write_text(
            _patch_for(empty_repo, FIXED_APP), encoding="utf-8")
        # the DEFAULT test command: discovery on a repo with no tests
        report2 = run_verification(
            _write_json(self.work / "rq.json", request),
            patch, empty_repo,
        )
        self.assertFalse(report2["verified"])
        self.assertTrue(report2["tests"]["ran"])
        self.assertFalse(report2["tests"]["passed"])
        self.assertNotEqual(report2["tests"]["returncode"], 0)
        # "Ran 0 tests" is printed by every supported Python; the
        # wording after it differs across versions.
        self.assertIn("Ran 0 tests", report2["tests"]["summary"])


class CliContractTests(unittest.TestCase):
    """Exit codes through the real CLI: 0 verified, 1 failed, 2 refused."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
